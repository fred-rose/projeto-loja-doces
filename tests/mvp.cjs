// Sem dependências de execução. Use uma instalação de Playwright já disponível.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  let checks = 0;
  const check = (value, expected, label) => { assert.deepEqual(value, expected, label); checks++; console.log('OK: '+label); };
  try {
    const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const url = process.env.TEST_URL || pathToFileURL(path.resolve('index.html')).href;
    await page.goto(url);
    const row = page.locator('.item').first();
    const field = name => row.locator('[data-field="'+name+'"]');
    const edit = async (name, value) => { await field(name).fill(value); await field(name).press('Tab'); };
    check(await page.locator('.item').count(), 4, 'quatro produtos de demonstração');
    check(await page.locator('#kpiTarget').innerText(), '360', 'meta central 360 sem multiplicação por loja');
    check(await field('actual').inputValue(), '', 'embalados começam em branco');
    check(await field('produced').inputValue(), '', 'produzidos começam em branco');
    check(await row.locator('.status').innerText(), 'Sem apontamento', 'branco é sem apontamento');
    await edit('produced', '100');
    await edit('actual', '0');
    check(await row.locator('.balance').innerText(), '120', 'zero apura pendência de 120');
    check(await row.locator('.status').innerText(), 'Com pendência', 'zero difere de não preenchido');
    await edit('actual', '80');
    check(await row.locator('.balance').innerText(), '40', '120 menos 80 embalados resulta em 40');
    check(await page.locator('#kpiProduced').innerText(), '100', 'produção contabilizada uma vez');
    check(await page.locator('#kpiActual').innerText(), '80', 'embalagem contabilizada uma vez');
    await edit('actual', '101');
    check(await field('actual').inputValue(), '80', 'rejeita embalados acima da produção');
    await edit('produced', '79');
    check(await field('produced').inputValue(), '100', 'rejeita produção menor que embalados');
    await edit('produced', '-1');
    check(await field('produced').inputValue(), '100', 'rejeita valor negativo');
    await edit('produced', '1.5');
    check(await field('produced').inputValue(), '100', 'rejeita valor fracionário');
    await field('reason').selectOption('Aguardando embalagem');
    await row.locator('[data-action="note"]').click();
    await edit('note', '=HYPERLINK("exemplo"); teste <script>');
    await page.reload();
    check(await field('produced').inputValue(), '100', 'produção persiste após recarregar');
    check(await field('actual').inputValue(), '80', 'embalagem persiste após recarregar');
    check(await field('reason').inputValue(), 'Aguardando embalagem', 'motivo persiste');
    await row.locator('[data-action="note"]').click();
    check(await field('note').inputValue(), '=HYPERLINK("exemplo"); teste <script>', 'nota preservada como texto');
    const downloadEvent = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await downloadEvent;
    const csv = fs.readFileSync(await download.path(), 'utf8');
    check(csv.includes('"100";"80";"40"'), true, 'CSV contém produção, embalagem e saldo corretos');
    check(csv.includes('"\'=HYPERLINK'), true, 'CSV neutraliza fórmulas em texto livre');
    check(csv.includes('FICTICIAS'), true, 'CSV identifica origem fictícia');
    check(csv.split('\r\n').length, 5, 'CSV tem uma linha por produto, sem duplicar lojas');
    await page.locator('#storeFilter').selectOption('AN');
    check(await page.locator('#kpiTarget').innerText(), '360', 'filtro por loja preserva totais da fábrica');
    await row.locator('[data-action="edit"]').click();
    await page.locator('#target').fill('121');
    await page.locator('#planForm button[type="submit"]').click();
    check(await page.locator('#modal').evaluate(e=>e.open), true, 'impede distribuição diferente da meta');
    await page.locator('#target').fill('120');
    await page.locator('#alloc_AN').fill('0');
    await page.locator('#alloc_NO').fill('65');
    await page.locator('#planForm button[type="submit"]').click();
    check(await page.locator('.item').count(), 3, 'loja mostra apenas produtos com alocação positiva');
    check(await page.locator('#kpiTarget').innerText(), '240', 'totais do filtro somam produtos da loja uma vez');
    await page.locator('#storeFilter').selectOption('all');
    await page.locator('#search').fill('Morango');
    const filteredDownload = page.waitForEvent('download');
    await page.locator('#export').click();
    const filteredCSV = fs.readFileSync(await (await filteredDownload).path(), 'utf8');
    check(filteredCSV.split('\r\n').length, 2, 'CSV respeita filtro de busca');
    await page.locator('#search').fill('');
    await page.locator('#date').fill('2026-10-29');
    await page.locator('#date').press('Tab');
    check(await page.locator('.item').count(), 0, 'nova data não inventa apontamentos');
    await page.locator('#add').click();
    await page.locator('#name').fill('Doce de teste');
    await page.locator('#target').fill('5');
    await page.locator('#split').click();
    check(await page.locator('#alloc_AN').inputValue(), '2', 'divisão inteira distribui resto sem perda');
    await page.locator('#planForm button[type="submit"]').click();
    check(await page.locator('#kpiTarget').innerText(), '5', 'planejamento criado em outra data');
    await edit('produced','6'); await edit('actual','6');
    check(await row.locator('.status').innerText(), 'Acima da meta', 'excesso de produção identificado');
    check(await row.locator('.balance').innerText(), '0', 'excesso não gera saldo negativo');
    await edit('actual','');
    check(await row.locator('.status').innerText(), 'Sem apontamento', 'limpar campo restaura estado não preenchido');
    for (const width of [1440, 1024, 768, 390, 320]) {
      await page.setViewportSize({ width, height: 900 });
      check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), true, 'sem rolagem horizontal em '+width+'px');
    }
    fs.mkdirSync('artifacts', {recursive:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
    page.once('dialog', d=>d.accept());
    await page.locator('#reset').click();
    check(await page.locator('#kpiTarget').innerText(), '360', 'restauração retorna demonstração inicial');
    await page.setViewportSize({width:1440,height:1000});
    await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
    // Compatibilidade com o armazenamento da implementação original.
    await page.evaluate(()=>{const k='docefluxo-central-demo-v2',d=JSON.parse(localStorage.getItem(k));delete d.items[0].produced;d.items[0].actual=30;localStorage.setItem(k,JSON.stringify(d));});
    await page.reload();
    check(await field('actual').inputValue(), '30', 'apontamento da versão original é preservado');
    check(await field('produced').inputValue(), '', 'migração não inventa produção');
    await page.evaluate(()=>{Storage.prototype.setItem=function(){throw new DOMException('Sem espaço','QuotaExceededError');};});
    await edit('actual', '20');
    check(await page.locator('#storageWarning').isVisible(), true, 'falha de armazenamento mostra aviso persistente');
    check(await field('actual').inputValue(), '20', 'falha de armazenamento preserva edição na memória para exportar');
    check(errors, [], 'sem erros de JavaScript');
    await context.close();
    console.log('\n'+checks+' verificações passaram.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
